from datetime import date
from typing import Literal
from pydantic import BaseModel, Field


# ==========================================
# 1. Tool Input Models (Validated from LLM tool arguments)
# ==========================================

class ExpenseItem(BaseModel):
    amount: float = Field(
        ...,
        gt=0,
        description="The positive expense amount in INR (Rupees).",
    )
    category: str = Field(
        ...,
        min_length=1,
        description="Matched existing category or concise proposed new category in Title Case.",
    )
    is_new_category: bool = Field(
        default=False,
        description="True if proposed category is absent from existing list.",
    )
    merchant: str | None = Field(
        default=None,
        description="Identified store/vendor/platform (e.g., Swiggy, Uber, Zepto).",
    )
    spent_on: date = Field(
        ...,
        description="Date of expense in YYYY-MM-DD format.",
    )
    note: str | None = Field(
        default=None,
        description="Brief description of the purchase/service.",
    )


class LogExpenseArgs(BaseModel):
    """Arguments passed when the LLM invokes the `log_expense` tool."""

    expenses: list[ExpenseItem] = Field(
        ...,
        min_length=1,
        description="List of one or more extracted expense items.",
    )


class QueryAnalyticsArgs(BaseModel):
    """Arguments passed when the LLM invokes the `query_analytics` tool."""

    start_date: date = Field(
        ...,
        description="Start date inclusive (YYYY-MM-DD).",
    )
    end_date: date = Field(
        ...,
        description="End date inclusive (YYYY-MM-DD).",
    )
    category_name: str | None = Field(
        default=None,
        description="Optional category name if filtering by a single category.",
    )
    period_label: str = Field(
        ...,
        description="Human-readable label like 'Jan 2026', 'Last Week', or 'Today'.",
    )


class DeleteExpenseArgs(BaseModel):
    """Arguments passed when the LLM invokes the `delete_or_undo_expense` tool."""

    target: Literal["last", "specific", "all"] = Field(
        ...,
        description="'last' to delete the most recent expense, 'specific' when criteria are provided, or 'all' to delete all expenses.",
    )
    amount: float | None = Field(
        default=None,
        description="Amount of the specific expense to delete.",
    )
    merchant: str | None = Field(
        default=None,
        description="Vendor or merchant name to match.",
    )
    spent_on: date | None = Field(
        default=None,
        description="Date of the expense in YYYY-MM-DD format.",
    )
    start_date: date | None = Field(
        default=None,
        description="Start date inclusive (YYYY-MM-DD) for range deletion.",
    )
    end_date: date | None = Field(
        default=None,
        description="End date inclusive (YYYY-MM-DD) for range deletion.",
    )


class PlanDeletionArgs(BaseModel):
    """Arguments generated by the agent to target specific expenses for deletion."""

    sql_where_clause: str = Field(
        ...,
        description=(
            "A valid SQL WHERE clause filtering the 'expenses' table (aliased as 'e'). "
            "Examples: \"e.spent_on >= '2026-01-01' AND e.spent_on <= '2026-01-31'\", "
            "\"LOWER(e.merchant) LIKE '%swiggy%'\", or \"1=1\" for all expenses. "
            "DO NOT include 'WHERE' or user_id filter; user_id is injected automatically."
        ),
    )
    explanation: str = Field(
        ...,
        description="A concise summary of what is being deleted (e.g., 'all January 2026 expenses', 'last expense logged').",
    )


# ==========================================
# 2. Pipeline Result & Telemetry (For Repository Logging)
# ==========================================

class ToolCallPayload(BaseModel):
    name: Literal[
        "log_expense",
        "query_analytics",
        "delete_or_undo_expense",
        "plan_deletion",
    ]
    data: (
        LogExpenseArgs
        | QueryAnalyticsArgs
        | DeleteExpenseArgs
        | PlanDeletionArgs
    )


class LLMResult(BaseModel):
    result_type: Literal["tool_call", "text"]
    tool_call: ToolCallPayload | None = None
    text_content: str | None = None
    raw_response: str = ""
    latency_ms: int = 0
    prompt_tokens: int | None = None
    completion_tokens: int | None = None
    total_tokens: int | None = None
    model_name: str = ""
    status: Literal["success", "error"] = "success"
    error_message: str | None = None